//! OS registration of schedules (AUT-02). Owner: W3-E.
//!
//! Generation is pure and tested; [`install`] / [`uninstall`] run only on an
//! explicit user action (CLI `schedule install`). Registered jobs run
//! `myjanitor-cli run-profile <id>` (the id, not the name: it never needs quoting).
//!
//! * Windows: `schtasks.exe` per user (no admin, no `/RU`), task `MyJanitor\<id>`.
//! * Linux: a systemd user service + timer under `$XDG_CONFIG_HOME/systemd/user/`;
//!   a crontab line is generated as the fallback for systems without systemd.

use std::path::PathBuf;

use mj_core::{Cadence, Error, Result, Schedule};

use crate::paths::{EnvMap, Os};
use crate::settings::os::{remove_if_ours, run_checked, write_generated, Cmd, GeneratedFile, Runner};

/// Marker line in generated unit files (checked before deleting one).
pub const MARKER: &str = "Generated by MyJanitor";

/// What the registered job should run.
#[derive(Debug, Clone)]
pub struct Ctx {
    /// Absolute path of `myjanitor-cli`.
    pub cli_exe: PathBuf,
    /// Passed as `--data-dir` when the data folder is not the default (portable, custom).
    pub data_dir: Option<PathBuf>,
}

const DAYS: [&str; 7] = ["MON", "TUE", "WED", "THU", "FRI", "SAT", "SUN"];

/// `MyJanitor\<id>`.
pub fn task_name(id: &str) -> String {
    format!("MyJanitor\\{id}")
}

fn clock(c: &Cadence) -> String {
    let (h, m) = match *c {
        Cadence::Daily { hour, minute }
        | Cadence::Weekly { hour, minute, .. }
        | Cadence::Monthly { hour, minute, .. } => (hour, minute),
    };
    format!("{h:02}:{m:02}")
}

fn ensure_id(id: &str) -> Result<()> {
    if !id.is_empty() && id.chars().all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-') {
        Ok(())
    } else {
        Err(Error::InvalidInput(format!("schedule id \"{id}\" is not a plain identifier; save the schedule again")))
    }
}

/// The command line the scheduled job runs (Windows quoting).
pub fn windows_task_command(id: &str, ctx: &Ctx) -> String {
    let mut s = format!("\"{}\" run-profile {id}", ctx.cli_exe.display());
    if let Some(d) = &ctx.data_dir {
        s.push_str(&format!(" --data-dir \"{}\"", d.display()));
    }
    s
}

/// `schtasks /Create` for the schedule.
pub fn schtasks_create(s: &Schedule, ctx: &Ctx) -> Result<Cmd> {
    ensure_id(&s.id)?;
    let mut a: Vec<String> = ["/Create", "/TN"].map(String::from).to_vec();
    a.push(task_name(&s.id));
    a.push("/TR".into());
    a.push(windows_task_command(&s.id, ctx));
    match s.cadence {
        Cadence::Daily { .. } => a.extend(["/SC", "DAILY"].map(String::from)),
        Cadence::Weekly { weekday, .. } => {
            a.extend(["/SC".into(), "WEEKLY".into(), "/D".into(), DAYS[(weekday as usize - 1) % 7].into()])
        }
        Cadence::Monthly { day, .. } => a.extend(["/SC".into(), "MONTHLY".into(), "/D".into(), day.to_string()]),
    }
    a.extend(["/ST".into(), clock(&s.cadence), "/F".into()]);
    Ok(Cmd::new("schtasks.exe", a))
}

/// `schtasks /Delete`.
pub fn schtasks_delete(id: &str) -> Cmd {
    Cmd::new("schtasks.exe", ["/Delete", "/TN", &task_name(id), "/F"].map(String::from).to_vec())
}

/// `schtasks /Query`.
pub fn schtasks_query(id: &str) -> Cmd {
    Cmd::new("schtasks.exe", ["/Query", "/TN", &task_name(id)].map(String::from).to_vec())
}

/// `(service, timer)` unit file names.
pub fn unit_names(id: &str) -> (String, String) {
    (format!("myjanitor-{id}.service"), format!("myjanitor-{id}.timer"))
}

/// Quote one `ExecStart=` word for systemd (`"..."`, `\` `"` escaped, `%` and `$` doubled).
pub fn systemd_quote(s: &str) -> String {
    let mut o = String::from("\"");
    for c in s.chars() {
        match c {
            '\\' => o.push_str("\\\\"),
            '"' => o.push_str("\\\""),
            '%' => o.push_str("%%"),
            '$' => o.push_str("$$"),
            _ => o.push(c),
        }
    }
    o.push('"');
    o
}

/// `OnCalendar=` expression (local time).
pub fn on_calendar(c: &Cadence) -> String {
    let t = format!("{}:00", clock(c));
    match *c {
        Cadence::Daily { .. } => format!("*-*-* {t}"),
        Cadence::Weekly { weekday, .. } => {
            let d = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"][(weekday as usize - 1) % 7];
            format!("{d} *-*-* {t}")
        }
        Cadence::Monthly { day, .. } => format!("*-*-{day:02} {t}"),
    }
}

fn one_line(s: &str) -> String {
    s.chars().map(|c| if c.is_control() { ' ' } else { c }).collect()
}

/// The `.service` unit.
pub fn systemd_service(s: &Schedule, ctx: &Ctx) -> String {
    let mut exec = format!("{} run-profile {}", systemd_quote(&ctx.cli_exe.display().to_string()), s.id);
    if let Some(d) = &ctx.data_dir {
        exec.push_str(&format!(" --data-dir {}", systemd_quote(&d.display().to_string())));
    }
    format!("# {MARKER}\n[Unit]\nDescription=MyJanitor scheduled profile: {}\n\n[Service]\nType=oneshot\nExecStart={exec}\n", one_line(&s.name))
}

/// The `.timer` unit.
pub fn systemd_timer(s: &Schedule) -> String {
    let (service, _) = unit_names(&s.id);
    format!(
        "# {MARKER}\n[Unit]\nDescription=MyJanitor schedule: {}\n\n[Timer]\nOnCalendar={}\nPersistent=true\nUnit={service}\n\n[Install]\nWantedBy=timers.target\n",
        one_line(&s.name),
        on_calendar(&s.cadence)
    )
}

/// A crontab line (fallback; never installed automatically).
pub fn crontab_line(s: &Schedule, ctx: &Ctx) -> String {
    let (h, m) = match s.cadence {
        Cadence::Daily { hour, minute }
        | Cadence::Weekly { hour, minute, .. }
        | Cadence::Monthly { hour, minute, .. } => (hour, minute),
    };
    let (dom, dow) = match s.cadence {
        Cadence::Daily { .. } => ("*".to_string(), "*".to_string()),
        Cadence::Weekly { weekday, .. } => ("*".into(), (weekday % 7).to_string()),
        Cadence::Monthly { day, .. } => (day.to_string(), "*".into()),
    };
    let q = |p: &str| format!("'{}'", p.replace('\'', "'\\''"));
    let mut cmd = format!("{} run-profile {}", q(&ctx.cli_exe.display().to_string()), s.id);
    if let Some(d) = &ctx.data_dir {
        cmd.push_str(&format!(" --data-dir {}", q(&d.display().to_string())));
    }
    format!("{m} {h} {dom} * {dow} {cmd}")
}

/// Systemd user unit directory.
pub fn systemd_dir(env: &EnvMap) -> Option<PathBuf> {
    let var = |k: &str| env.get(k).filter(|v| !v.is_empty()).map(PathBuf::from);
    var("XDG_CONFIG_HOME")
        .filter(|p| p.is_absolute())
        .or_else(|| var("HOME").map(|h| h.join(".config")))
        .map(|c| c.join("systemd").join("user"))
}

/// What installing does.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct Plan {
    pub commands: Vec<Cmd>,
    pub files: Vec<GeneratedFile>,
    /// Commands the user should run themselves afterwards.
    pub suggested: Vec<String>,
    /// Crontab alternative (Linux).
    pub crontab: Option<String>,
}

/// Plan an installation (pure).
pub fn plan_install(os: Os, env: &EnvMap, s: &Schedule, ctx: &Ctx) -> Result<Plan> {
    ensure_id(&s.id)?;
    match os {
        Os::Windows => Ok(Plan { commands: vec![schtasks_create(s, ctx)?], ..Plan::default() }),
        Os::Linux => {
            let dir = systemd_dir(env)
                .ok_or_else(|| Error::unsupported("scheduling", "no home folder: set HOME or XDG_CONFIG_HOME"))?;
            let (svc, tmr) = unit_names(&s.id);
            Ok(Plan {
                files: vec![
                    GeneratedFile { path: dir.join(&svc), content: systemd_service(s, ctx), executable: false },
                    GeneratedFile { path: dir.join(&tmr), content: systemd_timer(s), executable: false },
                ],
                suggested: vec![
                    "systemctl --user daemon-reload".into(),
                    format!("systemctl --user enable --now {tmr}"),
                ],
                crontab: Some(crontab_line(s, ctx)),
                ..Plan::default()
            })
        }
    }
}

/// Plan a removal (pure).
pub fn plan_uninstall(os: Os, id: &str) -> Result<Plan> {
    ensure_id(id)?;
    match os {
        Os::Windows => Ok(Plan { commands: vec![schtasks_delete(id)], ..Plan::default() }),
        Os::Linux => {
            let (_, tmr) = unit_names(id);
            Ok(Plan {
                suggested: vec![
                    format!("systemctl --user disable --now {tmr}"),
                    "systemctl --user daemon-reload".into(),
                ],
                ..Plan::default()
            })
        }
    }
}

/// Install: run the commands or write the unit files. Returns the suggested follow-up commands.
pub fn install(s: &Schedule, ctx: &Ctx, runner: &dyn Runner) -> Result<Vec<String>> {
    if crate::settings::os::os_integration_disabled() {
        return Err(Error::unsupported(
            "scheduling",
            format!("disabled by {}", crate::settings::os::NO_OS_INTEGRATION_VAR),
        ));
    }
    let plan = plan_install(Os::current(), &crate::paths::current_env(), s, ctx)?;
    for c in &plan.commands {
        run_checked(runner, c)?;
    }
    plan.files.iter().try_for_each(write_generated)?;
    Ok(plan.suggested)
}

/// Uninstall: delete the task or our unit files. Returns suggested follow-up commands.
pub fn uninstall(id: &str, runner: &dyn Runner) -> Result<Vec<String>> {
    let env = crate::paths::current_env();
    let plan = plan_uninstall(Os::current(), id)?;
    for c in &plan.commands {
        let _ = runner.run(c)?; // a missing task is already uninstalled
    }
    if Os::current() == Os::Linux {
        if let Some(dir) = systemd_dir(&env) {
            let (svc, tmr) = unit_names(id);
            remove_if_ours(&dir.join(tmr), MARKER)?;
            remove_if_ours(&dir.join(svc), MARKER)?;
        }
    }
    Ok(plan.suggested)
}

/// Whether the schedule is registered (Windows: query; Linux: timer file present).
pub fn is_installed(id: &str, runner: &dyn Runner) -> bool {
    if ensure_id(id).is_err() {
        return false;
    }
    if cfg!(windows) {
        runner.run(&schtasks_query(id)).map(|o| o.ok).unwrap_or(false)
    } else {
        systemd_dir(&crate::paths::current_env()).is_some_and(|d| d.join(unit_names(id).1).is_file())
    }
}

/// Write/remove helper used by tests with an explicit base folder.
pub fn write_plan_files(plan: &Plan) -> Result<()> {
    plan.files.iter().try_for_each(write_generated)
}

#[cfg(test)]
mod tests {
    use mj_core::testutil::TempDir;
    use mj_core::ScanScope;

    use super::*;

    fn sched(cadence: Cadence) -> Schedule {
        Schedule {
            id: "sched_3".into(),
            name: "Weekly\nDownloads".into(),
            enabled: true,
            cadence,
            scope: ScanScope::default(),
            steps: vec![],
            last_run: None,
            next_run: None,
        }
    }

    fn ctx() -> Ctx {
        Ctx { cli_exe: PathBuf::from("C:\\Program Files\\MyJanitor\\myjanitor-cli.exe"), data_dir: None }
    }

    #[test]
    fn schtasks_arguments_per_cadence() {
        let w = schtasks_create(&sched(Cadence::Weekly { weekday: 1, hour: 8, minute: 47 }), &ctx()).unwrap();
        assert_eq!(w.program, "schtasks.exe");
        assert_eq!(
            w.args,
            [
                "/Create",
                "/TN",
                "MyJanitor\\sched_3",
                "/TR",
                "\"C:\\Program Files\\MyJanitor\\myjanitor-cli.exe\" run-profile sched_3",
                "/SC",
                "WEEKLY",
                "/D",
                "MON",
                "/ST",
                "08:47",
                "/F"
            ]
        );
        let d = schtasks_create(&sched(Cadence::Daily { hour: 7, minute: 5 }), &ctx()).unwrap();
        assert!(d.args.windows(2).any(|p| p == ["/SC", "DAILY"]) && d.args.contains(&"07:05".to_string()));
        let m = schtasks_create(&sched(Cadence::Monthly { day: 15, hour: 0, minute: 0 }), &ctx()).unwrap();
        assert!(m.args.windows(2).any(|p| p == ["/SC", "MONTHLY"]) && m.args.windows(2).any(|p| p == ["/D", "15"]));
        // Per user: no run-as and no elevation flags.
        assert!(!w.args.iter().any(|a| a == "/RU" || a == "/RL"));
        let c = Ctx { data_dir: Some(PathBuf::from("D:\\mj data")), ..ctx() };
        assert!(windows_task_command("x", &c).ends_with("--data-dir \"D:\\mj data\""));
        assert_eq!(schtasks_delete("sched_3").args, ["/Delete", "/TN", "MyJanitor\\sched_3", "/F"]);
    }

    #[test]
    fn hostile_ids_are_refused() {
        let mut s = sched(Cadence::Daily { hour: 1, minute: 1 });
        s.id = "a\" & calc".into();
        assert!(schtasks_create(&s, &ctx()).is_err());
        assert!(plan_install(Os::Linux, &EnvMap::new(), &s, &ctx()).is_err());
    }

    #[test]
    fn systemd_units() {
        let s = sched(Cadence::Weekly { weekday: 1, hour: 8, minute: 47 });
        let c = Ctx { cli_exe: PathBuf::from("/opt/my%jan/myjanitor-cli"), data_dir: Some(PathBuf::from("/data/d")) };
        let svc = systemd_service(&s, &c);
        assert!(svc.contains("ExecStart=\"/opt/my%%jan/myjanitor-cli\" run-profile sched_3 --data-dir \"/data/d\""));
        assert!(svc.contains("Description=MyJanitor scheduled profile: Weekly Downloads"), "newlines are flattened");
        assert!(svc.contains("Type=oneshot") && svc.contains(MARKER));
        let t = systemd_timer(&s);
        assert!(t.contains("OnCalendar=Mon *-*-* 08:47:00") && t.contains("Persistent=true"));
        assert!(t.contains("Unit=myjanitor-sched_3.service") && t.contains("WantedBy=timers.target"));
        assert_eq!(on_calendar(&Cadence::Daily { hour: 9, minute: 0 }), "*-*-* 09:00:00");
        assert_eq!(on_calendar(&Cadence::Monthly { day: 5, hour: 9, minute: 30 }), "*-*-05 09:30:00");
        assert_eq!(on_calendar(&Cadence::Weekly { weekday: 7, hour: 1, minute: 2 }), "Sun *-*-* 01:02:00");
    }

    #[test]
    fn crontab_lines() {
        let c = Ctx { cli_exe: PathBuf::from("/usr/bin/myjanitor-cli"), data_dir: None };
        assert_eq!(
            crontab_line(&sched(Cadence::Weekly { weekday: 1, hour: 8, minute: 47 }), &c),
            "47 8 * * 1 '/usr/bin/myjanitor-cli' run-profile sched_3"
        );
        assert_eq!(
            crontab_line(&sched(Cadence::Weekly { weekday: 7, hour: 8, minute: 0 }), &c),
            "0 8 * * 0 '/usr/bin/myjanitor-cli' run-profile sched_3"
        );
        assert_eq!(
            crontab_line(&sched(Cadence::Monthly { day: 3, hour: 1, minute: 2 }), &c),
            "2 1 3 * * '/usr/bin/myjanitor-cli' run-profile sched_3"
        );
        assert_eq!(
            crontab_line(&sched(Cadence::Daily { hour: 1, minute: 2 }), &c),
            "2 1 * * * '/usr/bin/myjanitor-cli' run-profile sched_3"
        );
    }

    #[test]
    fn linux_plan_writes_a_pair_and_suggests_systemctl() {
        let t = TempDir::new("sched-os").unwrap();
        let env: EnvMap = [("XDG_CONFIG_HOME".to_string(), t.path().display().to_string())].into();
        let s = sched(Cadence::Daily { hour: 8, minute: 0 });
        let p = plan_install(Os::Linux, &env, &s, &Ctx { cli_exe: PathBuf::from("/x/cli"), data_dir: None }).unwrap();
        assert_eq!(p.files.len(), 2);
        assert!(p.files[1].path.ends_with("systemd/user/myjanitor-sched_3.timer"));
        assert!(p.suggested.iter().any(|c| c == "systemctl --user enable --now myjanitor-sched_3.timer"));
        assert!(p.crontab.is_some());
        write_plan_files(&p).unwrap();
        assert!(t.join("systemd/user/myjanitor-sched_3.service").is_file());
        // Only files carrying our marker are ever removed.
        let timer = t.join("systemd/user/myjanitor-sched_3.timer");
        assert!(remove_if_ours(&timer, MARKER).unwrap());
        std::fs::write(&timer, "foreign").unwrap();
        assert!(!remove_if_ours(&timer, MARKER).unwrap());
    }

    #[test]
    fn windows_plan_is_one_schtasks_command() {
        let p =
            plan_install(Os::Windows, &EnvMap::new(), &sched(Cadence::Daily { hour: 8, minute: 0 }), &ctx()).unwrap();
        assert_eq!(p.commands.len(), 1);
        assert!(p.files.is_empty());
        let u = plan_uninstall(Os::Windows, "sched_3").unwrap();
        assert_eq!(u.commands[0].args[0], "/Delete");
    }
}
